# Q2: the restructure — backfill, then simplified entry policy + 3-branch line policy.
# Sequencing is executed statement-by statement by the driver (see
# exp_q2_restructure): the tx-local superadmin GUC must be set while the
# OLD JournalEntry policies exist (they read app.is_superadmin), and the
# naive JournalEntryLine policy must already be dropped when the backfill
# runs (else the phase-1-style lines-EXISTS branch recurses through it).
# Prisma wraps each migration in one transaction — set_config(..., true)
# auto-reverts at COMMIT. Same mechanism as prisma/seed-rls.ts.
BACKFILL_GUARD_SQL = r"""
DO $$
DECLARE ambiguous int;
BEGIN
  SELECT count(*) INTO ambiguous FROM (
    SELECT jel."journalEntryId"
    FROM "JournalEntryLine" jel JOIN "Project" p ON p."id" = jel."projectId"
    WHERE jel."projectId" IS NOT NULL
    GROUP BY jel."journalEntryId"
    HAVING count(DISTINCT p."organizationId") > 1
  ) x;
  IF ambiguous > 0 THEN
    RAISE EXCEPTION 'backfill ambiguous: % entries have lines spanning multiple orgs', ambiguous;
  END IF;
END $$;
"""

BACKFILL_UPDATE_SQL = r"""
UPDATE "JournalEntry" je
SET "organizationId" = (
  SELECT p."organizationId"
  FROM "JournalEntryLine" jel
  JOIN "Project" p ON p."id" = jel."projectId"
  WHERE jel."journalEntryId" = je."id" AND jel."projectId" IS NOT NULL
  ORDER BY jel."lineNumber"
  LIMIT 1)
WHERE "organizationId" IS NULL;
"""

