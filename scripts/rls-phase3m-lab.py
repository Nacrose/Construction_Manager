def as_role(conn, role, org=None, superadmin=False):
    """Set role + org context on a connection (session-level GUCs)."""
    with conn.cursor() as cur:
        cur.execute("RESET ROLE;")
        if role:
            cur.execute(f'SET ROLE {role};')
        cur.execute("SELECT set_config('app.organization_id', %s, false)",
                    (org or "",))
        cur.execute("SELECT set_config('app.is_superadmin', %s, false)",
                    ("true" if superadmin else "false",))
    conn.commit()


def rows(conn, sql, params=None):
    with conn.cursor() as cur:
        cur.execute(sql, params or ())
        return cur.fetchall()


def scalar(conn, sql, params=None):
    r = rows(conn, sql, params)
    return r[0][0] if r else None


def expect_error(conn, sql, params=None, like=""):
    """Run in a rolled-back tx; return (raised, message)."""
    try:
        with conn.cursor() as cur:
            cur.execute("SAVEPOINT sp;")
            cur.execute(sql, params or ())
        conn.rollback()
        return False, ""
    except psycopg.errors.InsufficientPrivilege as e:
        conn.rollback()
        return True, str(e).strip()
    except psycopg.errors.CheckViolation as e:
        conn.rollback()
        return True, str(e).strip()
    except psycopg.Error as e:
        conn.rollback()
        return True, f"{type(e).__name__}: {e}".strip()


